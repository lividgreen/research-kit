def status(it):
    """The status column: MISSING for a needed item the machine or the project lacks, `--` for one that is
    absent and not needed yet, ok otherwise — the research plugin's probe reads the same."""
    return "MISSING" if not it["ok"] else "--     " if it["need"] == "absent" else "ok     "


def render_probe(rep):
    lines = [f"formal probe at {rep['root']}", "", "environment"]
    for it in rep["environment"]:
        lines.append(f"  {status(it)}  {it['item']} [{it['need']}]: {it['detail']}")
    lines += ["", "workspaces (a directory with a lakefile, to two levels under the root; one under it or required by path is a package of it)"]
    if not rep["workspaces"]:
        lines.append("  none; the formal plugin needs a Lean workspace")
    for w in rep["workspaces"]:
        lines.append(f"  {w['dir']}: package {w['package'] or 'UNNAMED'}; roots {', '.join(w['roots']) or 'NONE DECLARED'}; toolchain {w['toolchain'] or 'NO lean-toolchain'}; "
                     f"lake-manifest.json {'present' if w['manifest_lock'] else 'absent'}; DeclManifest.lean {'present' if w['generator'] else 'absent'}; "
                     f"instructions {', '.join(w['instructions']) or 'none (CLAUDE.md or AGENTS.md in the workspace)'}")
        for p in w["packages"][1:]:
            lines.append(f"    package {p['package'] or 'UNNAMED'} at {p['dir']}/: roots {', '.join(p['roots']) or 'NONE DECLARED'}; "
                         "Lake runs from the workspace, never from this directory")
    lines += ["", "project"]
    for it in rep["project"]:
        lines.append(f"  {status(it)}  {it['item']} [{it['need']}]: {it['detail']}")
    lines += ["", "proposals (nothing is installed or written by this probe)"]
    if not rep["proposals"]:
        lines.append("  nothing is missing")
    for p in rep["proposals"]:
        lines.append(f"  {p['item']} [{p['need']}]:")
        for c in p["commands"]:
            lines.append(f"    {c}")
    missing = [it["item"] for it in rep["environment"] + rep["project"] if not it["ok"] and it["need"] == "required"]
    lines += ["", f"formal probe: {len(rep['workspaces'])} workspace(s); " + (f"{len(missing)} required item(s) missing: {', '.join(missing)}" if missing else "every required item is present")
              + f"; {len(rep['proposals'])} proposal(s); the probe read the root and PATH and wrote nothing"]
    return "\n".join(lines)


