def render(sections, missing, cut, theorems_named, dotted, depth):
    out = [HEADER.format(depth=depth)]
    roots = [n for n, s in sections.items() if s["depth"] == 0]
    deps = [n for n, s in sections.items() if s["depth"] > 0]
    scoped = set()

    def emit_scope(s):
        if not s["scope"] or s["file"] in scoped:
            return
        scoped.add(s["file"])
        out.append(f"Scope lines preceding it in `{s['file']}`, in file order:\n\n```lean")
        for ln, txt in s["scope"]:
            out.append(f"-- line {ln}\n{txt}")
        out.append("```\n")

    out.append("## Declarations to read back\n")
    for n in roots:
        s = sections[n]
        out.append(f"### `{n}` — {s['file']}:{s['line']} ({s['kind']})\n")
        emit_scope(s)
        if s["instances"]:
            out.append("Instance binders, from the manifest (classes present; not a tier — see the packet's own "
                       "instructions above): " + ", ".join(f"`{c}`" for c in s["instances"]) + "\n")
        out.append(f"```lean\n{s['text']}\n```\n")
    out.append("## Project-local definitions the statements name\n")
    if not deps:
        out.append("(none resolved)\n")
    for n in deps:
        s = sections[n]
        out.append(f"### `{n}` — {s['file']}:{s['line']} ({s['kind']}, depth {s['depth']})\n")
        emit_scope(s)
        out.append(f"```lean\n{s['text']}\n```\n")
    if cut:
        out.append("## Named but not shown (beyond the depth bound)\n")
        out.append(", ".join(f"`{n}`" for n in cut) + "\n")
    if dotted:
        out.append("## Dot-notation names, NOT resolved\n")
        out.append("Written as a projection on a receiver whose type this packet does not elaborate. A project name "
                   "with the same last component exists and is listed so the reader knows the match was declined "
                   "rather than missed — it may well be a different definition. Read these by their use.\n")
        out.append("\n".join(f"* `{tok}` — matches by bare name: " + ", ".join(f"`{c}`" for c in sorted(cs))
                             for tok, cs in dotted.items()) + "\n")
    if theorems_named:
        out.append("## Theorems a statement names (listed, not shown)\n")
        out.append("\n".join(f"* `{n}` — {where}" for n, where in theorems_named.items()) + "\n")
    if missing:
        out.append("## Could not resolve\n")
        out.append("\n".join(f"* {m}" for m in missing) + "\n")
    return "\n".join(out)


def do_readback(cfg, names, out, depth):
    try:
        reader = Reader(cfg)
    except ManifestError as e:
        print(f"COULD NOT CHECK: {e}")
        return 2
    sections, missing, cut, thms, dots = reader.build(names, depth)
    text = render(sections, missing, cut, thms, dots, depth)
    if out:
        Path(out).write_text(text, encoding="utf-8")
        print(f"readback: packet written to {out} — {len([s for s in sections.values() if s['depth'] == 0])} "
              f"declaration(s), {len([s for s in sections.values() if s['depth'] > 0])} definition(s), {len(cut)} cut "
              f"by depth, {len(missing)} unresolved")
    else:
        print(text)
    return 1 if missing else 0


