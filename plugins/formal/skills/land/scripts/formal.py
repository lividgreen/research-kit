def views(rs):
    public, private, fields, mods = set(), set(), set(), {}
    for r in rs:
        if r.kind == "decl":
            public.add(r.name)
        elif r.kind == "private":
            private.add(r.name)
        elif r.kind == "field":
            fields.add(r.name)
        elif r.kind == "module":
            mods[r.module] = r.extra
    return public, private - public, fields, mods


def module_of(rs):
    return {r.name: r.module for r in rs if r.kind in ("decl", "private", "field")}


def owed(rs, base_rows=None, min_conditions=MIN_CONDITIONS):
    """(owed, witnessed): theorems with `min_conditions`+ named conditions, split by whether a
    `<theorem>_nonvacuous` exists; with `base_rows`, only theorems absent from the base."""
    conds, names = defaultdict(list), set()
    for r in rs:
        if r.kind == "hypothesis":
            conds[r.name].append(r.extra)
        elif r.kind in ("decl", "private"):
            names.add(r.name)
    base = {r.name for r in base_rows if r.kind in ("decl", "private")} if base_rows else set()
    owed_list, witnessed = [], []
    for thm, cs in sorted(conds.items()):
        if len(cs) < min_conditions or (base_rows is not None and thm in base):
            continue
        (witnessed if thm + WITNESS_SUFFIX in names else owed_list).append((thm, cs))
    return owed_list, witnessed


def commission(text):
    names = commissioned_names(text)
    if names is not None:
        return names, "its Commissioned line"
    found = SIGNATURE.findall(text) + WITNESS.findall(text)
    return list(dict.fromkeys(found)), "declaration keywords and witnesses (no Commissioned line)"


def sort_commission(names, base_names, head_names):
    landed, existing, absent = [], [], []
    for n in names:
        if matches_in(n, head_names - base_names):
            landed.append(n)
        elif matches_in(n, head_names):
            existing.append(n)
        else:
            absent.append(n)
    return landed, existing, absent


def instantiations(new_names, base_public):
    """A new name `P_x` under an existing public `P` of the same namespace, longest prefix first."""
    generics = sorted(base_public, key=len, reverse=True)
    inst = defaultdict(list)
    for n in new_names:
        base = n.split(".")[-1]
        for g in generics:
            gb = g.split(".")[-1]
            if base.startswith(gb + "_") and n.rsplit(".", 1)[0] == g.rsplit(".", 1)[0]:
                inst[g].append(n)
                break
    return inst


STALE_TOLERANCE = 2.0  # seconds


def module_of_file(cfg, f, known):
    """The module a `.lean` path relative to the root holds: under a bound package's root, or, where no
    package binds it, under the workspace as `module_path` reads it, if the manifest knows the module."""
    if not f.endswith(".lean"):
        return None
    for root, pdir in cfg.packages.items():
        p_rel = pdir.relative_to(cfg.root).as_posix()
        prefix = "" if p_rel in ("", ".") else p_rel.rstrip("/") + "/"
        if f.startswith(prefix + root + "/") or f == prefix + root + ".lean":
            return f[len(prefix):-5].replace("/", ".")
    ws_rel = cfg.workspace.relative_to(cfg.root).as_posix()
    ws_prefix = "" if ws_rel in ("", ".") else ws_rel.rstrip("/") + "/"
    if f.startswith(ws_prefix) and (mod := f[len(ws_prefix):-5].replace("/", ".")) in known:
        return mod
    return None


def declares_nothing(text):
    """True for Lean text with no declaration line outside its comments, an anonymous instance counted —
    an umbrella of imports and guards, whose edits never change a manifest's rows."""
    return not any(DECL_ANY.match(ln) for ln in strip_comments(text).splitlines())


def stale_manifests(cfg, edited, known):
    """(manifest, newest edited file) for each manifest older than an edited module of its own package:
    a manifest owns the roots its module rows name, and a root no manifest names yet falls to the
    manifests of its package directory, else to every manifest.  A module already in the manifest whose
    file declares nothing (imports and guards) is left out."""
    owns = {}
    for m in cfg.manifests:
        try:
            owns[m] = {r.module.split(".")[0] for r in rows_from_text(m.read_text(encoding="utf-8"), m.name) if r.kind == "module"}
        except (OSError, ManifestError):
            owns[m] = set()
    newest = {}
    for f in edited:
        mod = module_of_file(cfg, f, known)
        # an umbrella of imports and guards, before the edit and after it: deleting a module's last
        # declaration leaves a file that declares nothing, and that edit changes the manifest
        if mod in known and declares_nothing((cfg.root / f).read_text(encoding="utf-8", errors="replace")):
            was = git(cfg, "show", f"HEAD:./{f}")
            if was.returncode == 0 and declares_nothing(was.stdout):
                continue
        root = mod.split(".")[0]
        owners = [m for m in cfg.manifests if root in owns[m]]
        if not owners and root in cfg.packages:
            owners = [m for m in cfg.manifests if any(cfg.packages.get(r) == cfg.packages[root] for r in owns[m])]
        t = (cfg.root / f).stat().st_mtime
        for m in owners or cfg.manifests:
            if m not in newest or t > newest[m][1]:
                newest[m] = (f, t)
    # a tolerance: git writes a stash or a checkout in path order, so the manifest may be a moment older
    return [(m, f) for m, (f, t) in newest.items() if m.is_file() and m.stat().st_mtime + STALE_TOLERANCE < t]


def git(cfg, *args):
    return subprocess.run(["git", *args], cwd=cfg.root, capture_output=True, encoding="utf-8", errors="replace")


def do_handback(cfg, base, handoff):
    handoff_text = None
    if handoff:
        try:
            handoff_text = Path(handoff).read_text(encoding="utf-8")
        except OSError as e:
            print(f"COULD NOT CHECK: unreadable handoff draft ({e})")
            return 2
    g = git(cfg, "rev-parse", "--verify", "--quiet", base)
    if g.returncode != 0:
        why = (g.stderr.strip().splitlines() or ["not a git repository, or no such revision"])[0]
        print(f"COULD NOT CHECK: {base} is not a revision of a git repository at {cfg.root} ({why})")
        return 2
    try:
        base_rows = rows_at(cfg, base)
        if not base_rows:
            print(f"COULD NOT CHECK: no manifest at {base}")
            return 2
        head_rows = list(rows(cfg))
    except ManifestError as e:
        print(f"COULD NOT CHECK: {e}")
        return 2
    ws_rel = cfg.workspace.relative_to(cfg.root).as_posix()
    known = {r.module for r in base_rows + head_rows if r.kind == "module"}
    untracked = [f for f in git(cfg, "ls-files", "--others", "--exclude-standard", "-z", "--", ws_rel).stdout.split("\0")
                 if f.endswith(".lean")]
    # the modules the manifest counts, edited since HEAD: a lakefile or a scratch file is not one
    edited = [f for f in git(cfg, "diff", "--name-only", "--relative", "-z", "HEAD", "--", ws_rel).stdout.split("\0") + untracked
              if (cfg.root / f).is_file() and module_of_file(cfg, f, known)]
    stale = stale_manifests(cfg, edited, known)
    if stale:
        print("COULD NOT CHECK: " + "; ".join(f"{m.relative_to(cfg.root).as_posix()} is older than {f}" for m, f in stale)
              + ", edited since HEAD — the manifest was not regenerated after the last change to its package, so it is "
              f"not the tree. Regenerate it ({cfg.generate or 'the command formal.toml binds in [manifest] generate'}) and run again.")
        return 2
    b_pub, b_priv, b_fld, b_mod = views(base_rows)
    h_pub, h_priv, h_fld, h_mod = views(head_rows)
    b_all, h_all = b_pub | b_priv, h_pub | h_priv
    h_module_of, b_module_of = module_of(head_rows), module_of(base_rows)
    new_pub, new_priv = sorted(h_pub - b_all), sorted(h_priv - b_all)
    removed = sorted(b_all - h_all)
    to_private, to_public = sorted(b_pub & h_priv), sorted(b_priv & h_pub)
    fld_add, fld_rm = sorted(h_fld - b_fld), sorted(b_fld - h_fld)
    mod_delta = {m: (b_mod.get(m), h_mod.get(m)) for m in set(b_mod) | set(h_mod) if b_mod.get(m) != h_mod.get(m)}
    inst = instantiations(new_pub + new_priv, b_pub)
    print(f"handback: manifest {base} -> working tree ({len(b_all)} -> {len(h_all)} declarations, "
          f"{len(b_mod)} -> {len(h_mod)} modules)")

    def block(title, names):
        print(f"\n{title} ({len(names)}):")
        for n in names:
            print(f"  {n}  [{h_module_of.get(n) or b_module_of.get(n)}]")

    block("NEW PUBLIC", new_pub)
    block("NEW PRIVATE", new_priv)
    block("REMOVED", removed)
    if to_private or to_public:
        block("VISIBILITY public -> private", to_private)
        block("VISIBILITY private -> public", to_public)
    if fld_add or fld_rm:
        block("FIELDS added", fld_add)
        block("FIELDS removed", fld_rm)
    if inst:
        print(f"\nINSTANTIATIONS of an existing generic ({sum(len(v) for v in inst.values())}) — a document boundary "
              "that says 'at X alone' is what these falsify:")
        for g, ns in sorted(inst.items()):
            print(f"  {g}")
            for n in ns:
                print(f"    <- {n}")
    if mod_delta:
        print(f"\nMODULE COUNTS changed ({len(mod_delta)}):")
        for m, (a, b) in sorted(mod_delta.items()):
            print(f"  {m}: {a} -> {b}")
    owed_new, witnessed_new = owed(head_rows, base_rows)
    print(f"\nJOINT-SATISFIABILITY WITNESSES: {len(owed_new)} new theorem(s) with {MIN_CONDITIONS}+ named conditions "
          f"and no `{WITNESS_SUFFIX}` sibling (owed, or the row says why not); {len(witnessed_new)} witnessed. Named "
          "conditions only — count the binders yourself for the rest.")
    for thm, cs in owed_new:
        print(f"  {thm}  ({', '.join(c.split('.')[-1] for c in cs)})")
    d = git(cfg, "diff", "-U0", base, "--", ws_rel)
    plus = minus = 0
    cur = ""
    for line in d.stdout.splitlines():
        if line.startswith("+++ b/"):
            cur = line[6:]
        elif cur.endswith(".lean"):
            if line.startswith("+#guard_msgs"):
                plus += 1
            elif line.startswith("-#guard_msgs"):
                minus += 1
    for f in untracked:
        plus += sum(1 for ln in (cfg.root / f).read_text(encoding="utf-8", errors="replace").splitlines() if ln.startswith("#guard_msgs"))
    if untracked:
        print("\nUNTRACKED Lean file(s) — counted in the guard delta below, invisible to every `git diff` above, and "
              "unseen by the commit hooks until staged:")
        for f in untracked:
            print(f"  {f}")
    print(f"\nGUARDS: +{plus} -{minus} since {base}. Where the project states a guard total, write the TOTAL, never "
          "'N new guards'; the project's figure check lists the sites.")
    touched = {h_module_of.get(n) or b_module_of.get(n)
               for n in new_pub + new_priv + removed + to_private + to_public + fld_add + fld_rm}
    changed = git(cfg, "diff", "--name-only", "--relative", "-z", base, "--", ws_rel).stdout.split("\0") + untracked
    touched |= {module_of_file(cfg, f, known) for f in changed}
    touched.discard(None)
    citable = h_pub | h_fld
    lost = set(to_private) | set(removed) | set(fld_rm)
    touched_names = {n for n in h_all | b_all | h_fld | b_fld if (h_module_of.get(n) or b_module_of.get(n)) in touched}
    print(f"\nTOUCHED MODULES ({len(touched)}): {', '.join(sorted(touched)) or '-'}")
    sites, private_hits = [], []
    for path in expand_globs(cfg, cfg.scan):
        rel = path.relative_to(cfg.root)
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        for lineno, line in enumerate(lines, 1):
            cited = False
            for m in TOKEN_BT.finditer(line):
                tok = m.group(1)
                hits = matches_in(tok, touched_names)
                if not hits:
                    continue
                cited = True
                cls = "row" if line.lstrip().startswith("|") else "BOUNDARY" if BOUNDARY.match(line) else "prose"
                sites.append((str(rel), lineno, tok, cls))
                # judged over the touched readings alone, so an unrelated public name elsewhere sharing the
                # last component does not cover a cited declaration that went private or was removed
                gone = not (hits & (h_all | h_fld))
                if private_only(tok, h_all, h_priv) or (hits & lost and not hits & citable):
                    private_hits.append((str(rel), lineno, tok + (" (REMOVED)" if gone else "")))
            st = STATEMENT.match(line)
            if cited and st:
                for k in range(lineno, min(lineno + BOUNDARY_REACH, len(lines))):
                    if BOUNDARY.match(lines[k]):
                        sites.append((str(rel), k + 1, f"boundary of {st.group(1)} {st.group(2)}", "BOUNDARY"))
                        break
                    if STATEMENT.match(lines[k]) and k > lineno:
                        break
    print(f"\nDOCUMENT SITES citing a touched module ({len(sites)}) — re-read each against the landed declaration's "
          "binders, the boundary paragraphs first:")
    by = defaultdict(list)
    for rel, ln, tok, cls in sites:
        by[(rel, cls)].append((ln, tok))
    for (rel, cls), items in sorted(by.items(), key=lambda kv: (kv[0][0], kv[0][1] != "BOUNDARY")):
        toks = ", ".join(f"{t}@{ln}" for ln, t in items[:12]) + (" …" if len(items) > 12 else "")
        print(f"  {rel} [{cls}] {len(items)}: {toks}")
    if handoff_text is not None:
        names, source = commission(handoff_text)
        landed, existing, absent = sort_commission(names, b_pub | b_fld, citable)
        private = [n for n in absent if matches_in(n, h_priv)]
        absent = [n for n in absent if n not in private]
        print(f"\nCOMMISSION against the manifest ({len(names)} name(s), read from {source}):")
        print(f"  landed ({len(landed)}): {', '.join(landed) or '-'}")
        print(f"  PRIVATE ({len(private)}) — in the tree but not citable; a row never names one: {', '.join(private) or '-'}")
        print(f"  at {base} already ({len(existing)}): {', '.join(existing) or '-'}")
        print(f"  ABSENT ({len(absent)}) — name each in the log entry under what did not land as commissioned, "
              f"whatever the report says: {', '.join(absent) or '-'}")
    else:
        print("\nCOMMISSION not compared: pass --handoff <the emitted prompt's draft>.")
    if private_hits:
        print("\nFAIL: a document cites a name that is now private only, or removed:")
        for rel, ln, tok in private_hits:
            print(f"  {rel}:{ln}: `{tok}`")
        return 1
    print("\nhandback: report complete (no document cites a now-private or removed name)")
    return 0


