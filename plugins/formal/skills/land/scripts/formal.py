def as_list(v):
    """A list binding; one string written where a list is meant is that one item, not its characters."""
    return [v] if isinstance(v, str) else list(v)


def find_root(start=None):
    p = Path(start or Path.cwd()).resolve()
    for cand in (p, *p.parents):
        if (cand / "formal.toml").is_file():
            return cand
    return p


# --- the manifest grammar -----------------------------------------------------------------

KINDS = ("module", "private", "field", "hypothesis", "instance", "decl")
Row = namedtuple("Row", "kind module name extra lineno raw")
# a field of a row: a run of non-space characters, a «…» part kept whole with any spaces inside it
FIELD = re.compile(r"(?:«[^»]*»|[^\s«])+")


class ManifestError(Exception):
    """An unparseable row, with its file and line."""


def rows_from_text(text, name="manifest"):
    """A `Row` per meaningful line; blank lines and `#` comments skipped; anything else raises."""
    for lineno, raw in enumerate(text.splitlines(), 1):
        s = raw.strip()
        if not s or s.startswith("#"):
            continue
        p = FIELD.findall(s)
        if not p or s.count("«") != s.count("»"):
            raise ManifestError(f"{name}:{lineno} has an unclosed «…» name: {raw!r}")
        if p[0] == "module" and len(p) == 3 and re.fullmatch(r"[0-9]+", p[2]):
            yield Row("module", p[1], None, int(p[2]), lineno, raw)
        elif p[0] == "private" and len(p) == 3:
            yield Row("private", p[1], p[2], None, lineno, raw)
        elif p[0] == "field" and len(p) == 3:
            yield Row("field", p[1], p[2], None, lineno, raw)
        elif p[0] == "hypothesis" and len(p) == 4:
            yield Row("hypothesis", p[1], p[2], p[3], lineno, raw)
        elif p[0] == "instance" and len(p) == 4:
            yield Row("instance", p[1], p[2], p[3], lineno, raw)
        elif len(p) == 2 and p[0] not in KINDS:
            yield Row("decl", p[0], p[1], None, lineno, raw)
        else:
            raise ManifestError(f"{name}:{lineno} matches no known row kind ({', '.join(KINDS)}): {raw!r}")


def rows(cfg, path=None):
    """Every row of the bound manifests (or of one file)."""
    files = [Path(path)] if path else cfg.manifests
    for m in files:
        if not m.is_file():
            raise ManifestError(f"missing {m} — regenerate it in the workspace: {cfg.generate or 'the project binds the command in formal.toml'}")
        yield from rows_from_text(m.read_text(encoding="utf-8"), m.name)


def rows_at(cfg, rev):
    """The rows of the bound manifests at a git revision; a file absent there is skipped."""
    out = []
    for m in cfg.manifests:
        rel = m.relative_to(cfg.root).as_posix()
        # `./` reads the path from the project root, which need not be the repository's top level
        r = subprocess.run(["git", "show", f"{rev}:./{rel}"], cwd=cfg.root, capture_output=True, encoding="utf-8")
        if r.returncode == 0:
            out.extend(rows_from_text(r.stdout, f"{m.name}@{rev}"))
    return out


def module_path(cfg, module):
    """`Root.X.Y` at `<package dir>/Root/X/Y.lean`; the root itself at `<package dir>/Root.lean`."""
    d = cfg.packages.get(module.split(".")[0], cfg.workspace)
    return d / (module.replace(".", "/") + ".lean")


def matches_in(tok, pool):
    """Every manifest name in `pool` a bare citation `tok` could denote."""
    return {n for n in pool if n == tok or n.endswith("." + tok) or n.split(".")[-1] == tok}


def private_only(tok, pool, private):
    """True when every name `tok` could denote is private — a citation with no public reading."""
    hits = matches_in(tok, pool)
    return bool(hits) and hits <= private


