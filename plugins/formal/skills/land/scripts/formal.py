PROBE_SKIP = {".git", ".lake", "node_modules", ".venv", "build", "dist"}
LIB_RE = re.compile(r"lean_lib\s+(?:«([^»]+)»|([A-Za-z_][\w.]*))")


def lake_roots(ws):
    """The library roots a workspace's lakefile declares (lakefile.toml's [[lean_lib]] names, or
    lakefile.lean's `lean_lib` declarations), and the package name."""
    toml = ws / "lakefile.toml"
    if toml.is_file():
        try:
            raw = tomllib.loads(toml.read_text(encoding="utf-8"))
        except (tomllib.TOMLDecodeError, UnicodeDecodeError):
            return None, []
        return raw.get("name"), [str(lib.get("name")) for lib in raw.get("lean_lib", []) if lib.get("name")]
    lean = ws / "lakefile.lean"
    if lean.is_file():
        text = lean.read_text(encoding="utf-8", errors="replace")
        m = re.search(r"package\s+(?:«([^»]+)»|([A-Za-z_][\w.]*))", text)
        return (m.group(1) or m.group(2)) if m else None, [a or b for a, b in LIB_RE.findall(text)]
    return None, []


def probe(root):
    """What the project and the machine have for the prover side, and what the setup needs that is
    missing.  Writes nothing; the `formal-init` skill reads it."""
    env = []
    for tool, need in (("git", "required"), ("lake", "required"), ("lean", "required"), ("elan", "recommended")):
        where = shutil.which(tool)
        env.append({"item": tool, "need": need, "ok": where is not None,
                    "detail": where or ("not on PATH" + ("; the manifest generator runs through it" if tool == "lake" else "; elan installs lean and lake per the workspace's lean-toolchain" if tool == "elan" else ""))})
    workspaces = []
    for dirpath, dirnames, filenames in os.walk(root):
        rel = Path(dirpath).relative_to(root)
        dirnames[:] = sorted(d for d in dirnames if d not in PROBE_SKIP and not d.startswith("."))
        if len(rel.parts) >= 2:
            dirnames[:] = []
        if "lakefile.toml" in filenames or "lakefile.lean" in filenames:
            ws = Path(dirpath)
            name, roots = lake_roots(ws)
            tc = (ws / "lean-toolchain").read_text(encoding="utf-8", errors="replace").strip() if (ws / "lean-toolchain").is_file() else None
            instr = [f for f in ("CLAUDE.md", "AGENTS.md") if (ws / f).is_file()]
            workspaces.append({"dir": rel.as_posix() if rel.parts else ".", "package": name, "roots": roots, "toolchain": tc,
                               "manifest_lock": (ws / "lake-manifest.json").is_file(), "generator": (ws / "DeclManifest.lean").is_file(),
                               "instructions": instr})
    proj = []
    has_formal = (root / "formal.toml").is_file()
    proj.append({"item": "formal.toml", "need": "present" if has_formal else "absent", "ok": True,
                 "detail": "the prover side is bound; `formal init` would refuse without --force" if has_formal else "not written yet; `formal init --workspace DIR` writes it"})
    flow_toml = root / "flow.toml"
    if flow_toml.is_file():
        try:
            ev = tomllib.loads(flow_toml.read_text(encoding="utf-8")).get("evidence", {})
        except (tomllib.TOMLDecodeError, UnicodeDecodeError):
            ev = {}
        bound = bool(ev.get("manifest"))
        proj.append({"item": "flow.toml [evidence]", "need": "required", "ok": bound,
                     "detail": f"manifest {ev.get('manifest')} bound" if bound else "the flow resolves no declaration evidence yet; bind `manifest`, `manifest_roots` and `manifest_extension = \"lean\"`"})
    else:
        proj.append({"item": "flow.toml", "need": "required", "ok": False, "detail": "no flow.toml at the root; the research plugin's init comes first"})
    mcp = root / ".mcp.json"
    lsp = False
    if mcp.is_file():
        try:
            servers = json.loads(mcp.read_text(encoding="utf-8")).get("mcpServers", {})
            lsp = any("lean" in json.dumps(s).lower() for s in servers.values())
        except (ValueError, AttributeError):
            lsp = False
    proj.append({"item": "prover language server (.mcp.json)", "need": "recommended", "ok": lsp,
                 "detail": "a server naming lean is registered" if lsp else ("no .mcp.json at the root" if not mcp.is_file() else "no server naming lean in .mcp.json") + "; the prover agent uses whatever prover tools are registered"})
    pc = root / ".pre-commit-config.yaml"
    hook = pc.is_file() and "formal-check" in pc.read_text(encoding="utf-8", errors="replace")
    proj.append({"item": "formal-check hook", "need": "required", "ok": hook,
                 "detail": "named in .pre-commit-config.yaml" if hook else ("not in .pre-commit-config.yaml" if pc.is_file() else "no .pre-commit-config.yaml") + "; `formal check` runs before a commit"})
    proj.append({"item": "documents", "need": "present" if (root / "papers").is_dir() else "absent", "ok": True,
                 "detail": "papers/ exists, the default `[documents] scan`" if (root / "papers").is_dir() else "no papers/ directory; `[documents] scan` names the documents' globs"})
    proposals = []
    if not shutil.which("lake") or not shutil.which("lean"):
        proposals.append({"item": "lean and lake", "need": "required", "commands": ["elan, from https://github.com/leanprover/elan, then `elan toolchain install $(cat lean-toolchain)` in the workspace"]})
    if not lsp:
        ws0 = workspaces[0]["dir"] if workspaces else "<workspace>"
        proposals.append({"item": "prover language server", "need": "recommended",
                          "commands": ['.mcp.json at the project root: {"mcpServers": {"lean-lsp": {"type": "stdio", "command": "uvx", "args": ["lean-lsp-mcp", "--lean-project-path", "' + ws0 + '"]}}}  (an absolute path where the agent runs from elsewhere)']})
    for w in workspaces:
        if not w["generator"]:
            roots = ",".join(w["roots"]) or "<Root>"
            proposals.append({"item": f"manifest of {w['dir']}", "need": "required",
                              "commands": [f"copy DeclManifest.lean from the land skill into {w['dir']}/, then in it after a build: lake env lean --run DeclManifest.lean --roots {roots} --out ../scripts/decls.txt"]})
    return {"root": str(root), "environment": env, "workspaces": workspaces, "project": proj, "proposals": proposals}


def render_probe(rep):
    lines = [f"formal probe at {rep['root']}", "", "environment"]
    for it in rep["environment"]:
        lines.append(f"  {'ok     ' if it['ok'] else 'MISSING'}  {it['item']} [{it['need']}]: {it['detail']}")
    lines += ["", "workspaces (a directory with a lakefile, to two levels under the root)"]
    if not rep["workspaces"]:
        lines.append("  none; the formal plugin needs a Lean workspace")
    for w in rep["workspaces"]:
        lines.append(f"  {w['dir']}: package {w['package'] or 'UNNAMED'}; roots {', '.join(w['roots']) or 'NONE DECLARED'}; toolchain {w['toolchain'] or 'NO lean-toolchain'}; "
                     f"lake-manifest.json {'present' if w['manifest_lock'] else 'absent'}; DeclManifest.lean {'present' if w['generator'] else 'absent'}; "
                     f"instructions {', '.join(w['instructions']) or 'none (CLAUDE.md or AGENTS.md in the workspace)'}")
    lines += ["", "project"]
    for it in rep["project"]:
        lines.append(f"  {'ok     ' if it['ok'] else 'MISSING'}  {it['item']} [{it['need']}]: {it['detail']}")
    lines += ["", "proposals (nothing is installed or written by this probe)"]
    if not rep["proposals"]:
        lines.append("  nothing is missing")
    for p in rep["proposals"]:
        lines.append(f"  {p['item']} [{p['need']}]:")
        for c in p["commands"]:
            lines.append(f"    {c}")
    missing = [it["item"] for it in rep["environment"] + rep["project"] if not it["ok"] and it["need"] == "required"]
    lines += ["", f"formal probe: {len(rep['workspaces'])} workspace(s); " + (f"{len(missing)} required item(s) missing: {', '.join(missing)}" if missing else "every required item is present")
              + f"; {len(rep['proposals'])} proposal(s); the probe read the root and PATH and wrote nothing"]
    return "\n".join(lines)


# --- main -----------------------------------------------------------------------------------

def main(argv=None):
    """The command line; a crash exits 2, could not run, never 1, which says problems were found."""
    try:
        return _main(argv)
    except Exception:
        traceback.print_exc()
        print("formal: could not run (the error above)", file=sys.stderr)
        return 2


def _main(argv=None):
    ap = argparse.ArgumentParser(prog="formal", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", help="the project root (default: found above the cwd by formal.toml)")
    ap.add_argument("--selftest", action="store_true")
    sp = ap.add_subparsers(dest="cmd")
    p = sp.add_parser("init"); p.add_argument("--workspace", default="formal"); p.add_argument("--force", action="store_true")
    sp.add_parser("check")
    p = sp.add_parser("handoffcheck"); p.add_argument("draft", nargs="?")
    p = sp.add_parser("handback"); p.add_argument("--base", default="HEAD"); p.add_argument("--handoff")
    p = sp.add_parser("readback"); p.add_argument("names", nargs="+"); p.add_argument("-o", "--out"); p.add_argument("--depth", type=int, default=2)
    p = sp.add_parser("probe", help="report the project and the machine against the prover side's setup; writes nothing"); p.add_argument("--json", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    if not a.cmd:
        ap.print_help()
        return 0
    if a.cmd == "probe":
        root = Path(a.root).resolve() if a.root else find_root()
        rep_ = probe(root)
        print(json.dumps(rep_, indent=1) if a.json else render_probe(rep_))
        return 0
    root = Path(a.root).resolve() if a.root else find_root()
    try:
        if a.cmd == "init":
            do_init(root, a.workspace, a.force)
            return 0
        if a.cmd == "handoffcheck":
            cfg = Config(root, allow_missing=True)
            text = Path(a.draft).read_text(encoding="utf-8") if a.draft else sys.stdin.read()
            try:
                problems, _ = check_handoff(text, cfg)
            except ValueError as e:
                print(f"COULD NOT CHECK: {e}")
                return 2
            if problems:
                for pr in problems:
                    print(f"HANDOFF {pr}")
                print(f"\n{len(problems)} violation(s). Fix and re-run before emitting.")
                return 1
            print("handoffcheck: structurally clean (content fidelity is still yours to re-read)"
                  + ("" if cfg.bound else "; no formal.toml found, the default bindings were used"))
            return 0
        try:
            cfg = Config(root)
        except (Refused, tomllib.TOMLDecodeError, UnicodeDecodeError) as e:  # no bindings to run on: could not run, not a problem found
            print(f"COULD NOT CHECK: {e}")
            return 2
        if a.cmd == "check":
            return do_check(cfg)
        if a.cmd == "handback":
            return do_handback(cfg, a.base, a.handoff)
        if a.cmd == "readback":
            return do_readback(cfg, a.names, a.out, a.depth)
    except Refused as e:
        print(f"formal: refused — {e}")
        return 1
    except OSError as e:
        print(f"COULD NOT CHECK: {e}")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
