class Config:
    """The bindings of `formal.toml`; with `allow_missing`, defaults where the file is absent
    (the handoff check runs on a draft alone)."""

    def __init__(self, root, allow_missing=False):
        self.root = Path(root)
        path = self.root / "formal.toml"
        if path.is_file():
            raw = tomllib.loads(path.read_text(encoding="utf-8"))
            self.bound = True
        elif allow_missing:
            raw, self.bound = {}, False
        else:
            raise Refused(f"no formal.toml at {self.root} (`formal init` writes one)")
        ws = raw.get("workspace", {})
        self.workspace_name = ws.get("dir", "formal")
        self.workspace = self.root / self.workspace_name
        self.instructions = self.root / ws.get("instructions", f"{self.workspace_name}/AGENTS.md")
        mf = raw.get("manifest", {})
        self.manifests = [self.root / f for f in as_list(mf.get("files", ["scripts/decls.txt"]))]
        self.generate = mf.get("generate", "")
        self.packages = {r: self.workspace / d for r, d in raw.get("packages", {}).items()}
        docs = raw.get("documents", {})
        self.scan = as_list(docs.get("scan", ["papers/*.md"]))
        h = raw.get("handoff", {})
        self.root_dirs = tuple(as_list(h.get("root_dirs", ["papers", "docs"])))
        self.banned = tuple(as_list(h.get("banned", [])))
        self.records = h.get("records", "records")
        self.id_prefixes = tuple(as_list(h.get("id_prefixes", ["idea", "question", "task", "finding"])))


def as_list(v):
    """A list binding; one string written where a list is meant is that one item, not its characters."""
    return [v] if isinstance(v, str) else list(v)


def find_root(start=None):
    p = Path(start or Path.cwd()).resolve()
    for cand in (p, *p.parents):
        if (cand / "formal.toml").is_file():
            return cand
    return p


# --- the manifest grammar -----------------------------------------------------------------

KINDS = ("module", "private", "field", "hypothesis", "instance", "decl")
Row = namedtuple("Row", "kind module name extra lineno raw")
# a field of a row: a run of non-space characters, a «…» part kept whole with any spaces inside it
FIELD = re.compile(r"(?:«[^»]*»|[^\s«])+")


class ManifestError(Exception):
    """An unparseable row, with its file and line."""


def rows_from_text(text, name="manifest"):
    """A `Row` per meaningful line; blank lines and `#` comments skipped; anything else raises."""
    for lineno, raw in enumerate(text.splitlines(), 1):
        s = raw.strip()
        if not s or s.startswith("#"):
            continue
        p = FIELD.findall(s)
        if not p or s.count("«") != s.count("»"):
            raise ManifestError(f"{name}:{lineno} has an unclosed «…» name: {raw!r}")
        if p[0] == "module" and len(p) == 3 and re.fullmatch(r"[0-9]+", p[2]):
            yield Row("module", p[1], None, int(p[2]), lineno, raw)
        elif p[0] == "private" and len(p) == 3:
            yield Row("private", p[1], p[2], None, lineno, raw)
        elif p[0] == "field" and len(p) == 3:
            yield Row("field", p[1], p[2], None, lineno, raw)
        elif p[0] == "hypothesis" and len(p) == 4:
            yield Row("hypothesis", p[1], p[2], p[3], lineno, raw)
        elif p[0] == "instance" and len(p) == 4:
            yield Row("instance", p[1], p[2], p[3], lineno, raw)
        elif len(p) == 2 and p[0] not in KINDS:
            yield Row("decl", p[0], p[1], None, lineno, raw)
        else:
            raise ManifestError(f"{name}:{lineno} matches no known row kind ({', '.join(KINDS)}): {raw!r}")


def rows(cfg, path=None):
    """Every row of the bound manifests (or of one file)."""
    files = [Path(path)] if path else cfg.manifests
    for m in files:
        if not m.is_file():
            raise ManifestError(f"missing {m} — regenerate it in the workspace: {cfg.generate or 'the project binds the command in formal.toml'}")
        yield from rows_from_text(m.read_text(encoding="utf-8"), m.name)


def rows_at(cfg, rev):
    """The rows of the bound manifests at a git revision; a file absent there is skipped."""
    out = []
    for m in cfg.manifests:
        rel = m.relative_to(cfg.root).as_posix()
        # `./` reads the path from the project root, which need not be the repository's top level
        r = subprocess.run(["git", "show", f"{rev}:./{rel}"], cwd=cfg.root, capture_output=True, encoding="utf-8")
        if r.returncode == 0:
            out.extend(rows_from_text(r.stdout, f"{m.name}@{rev}"))
    return out


def module_path(cfg, module):
    """`Root.X.Y` at `<package dir>/Root/X/Y.lean`; the root itself at `<package dir>/Root.lean`."""
    d = cfg.packages.get(module.split(".")[0], cfg.workspace)
    return d / (module.replace(".", "/") + ".lean")


def matches_in(tok, pool):
    """Every manifest name in `pool` a bare citation `tok` could denote."""
    return {n for n in pool if n == tok or n.endswith("." + tok) or n.split(".")[-1] == tok}


def private_only(tok, pool, private):
    """True when every name `tok` could denote is private — a citation with no public reading."""
    hits = matches_in(tok, pool)
    return bool(hits) and hits <= private


# --- the handoff check --------------------------------------------------------------------

OPEN_TAG = re.compile(r"<prompt\b[^>]*>")
OPEN_TAG_VALID = re.compile(r"<prompt session=(fresh|continue)>")
CLOSE_TAG = "</prompt>"
REGISTER_WARNING = re.compile(
    r"docstring[^.\n]*\b(meta-doc|record|log|internal register)\b|\b(meta-doc|internal register)[^.\n]*docstring",
    re.IGNORECASE)
REGISTER_PASTE = ("The records named above are sources to READ, not citations: a docstring renders verbatim into "
                  "the public artifact, so it cites the document's section and row ids — never a record or the log.")
BUNDLE_WORDS_WARNING = re.compile(
    r"docstrings?[^.\n]*\b(?:name|mention|carry)\b[^.\n]*\b(?:no|never)\b[^.\n]*\b(?:piece|bundle|landing|session)",
    re.IGNORECASE)
BUNDLE_WORDS_PASTE = ("The docstrings name no piece of any handoff, no bundle, no landing, no session and no record: a "
                      "public docstring describes the mathematics, so the hypotheses are hypotheses and the assembly is "
                      "a conditional theorem, never \"the sink\", \"the predecessors\" or \"a later session\".")
MULTI_BUNDLE = re.compile(r"Bundle shape:\s*(?:\*\*)?\s*(?:sink-first|sequential)", re.IGNORECASE)
REFUTE_LINE = re.compile(r"^\s*(?:\*\*)?Refute first:", re.M)
REFUTE_PASTE = ("Refute first: <the smallest parameters at which the commissioned statement is computed> — or "
                "`Refute first: not applicable — <review/refactor/bump>`")
PIECE = re.compile(r"\b(?:Piece|Target)\s+(\d+)\b")
BUNDLE_LINE = re.compile(r"^\s*(?:\*\*)?Bundle shape:", re.M)
BUNDLE_PASTE = ("Bundle shape: sink-first — sink <name>, predecessors <names> (or `Bundle shape: single piece`, "
                "or `Bundle shape: sequential — <why not sink-first>`)")
COMMISSION_LINE = re.compile(r"^\s*(?:\*\*)?Commissioned:(?:\*\*)?(.*?)(?:\n\s*\n|\Z)", re.M | re.S)
COMMISSION_NONE = re.compile(r"^\s*none\b", re.IGNORECASE)
COMMISSION_NAME = re.compile(r"`([^`\s]+)`")
COMMISSION_PASTE = ("Commissioned: `<every declaration the prompt commissions, witnesses included>` — or "
                    "`Commissioned: none — <review/refactor/bump>`")


def commissioned_names(text):
    """The names a prompt's `Commissioned:` line lists; [] for `none`; None with no line."""
    m = COMMISSION_LINE.search(text)
    if not m:
        return None
    rest = m.group(1).strip()
    if COMMISSION_NONE.match(rest):
        return []
    return list(dict.fromkeys(COMMISSION_NAME.findall(rest)))


def line_of(text, pos):
    return text.count("\n", 0, pos) + 1


def check_handoff(text, cfg):
    """(problems, session) for one draft; raises ValueError with no prompt block at all."""
    opens = list(OPEN_TAG.finditer(text))
    if not opens:
        raise ValueError("no <prompt ...> block found in the input")
    problems = []
    if len(opens) > 1:
        problems.append("multiple opening tags (lines " + ", ".join(str(line_of(text, m.start())) for m in opens)
                        + "); a handoff is one block")
    tag = opens[0]
    m_valid = OPEN_TAG_VALID.fullmatch(tag.group(0))
    session = m_valid.group(1) if m_valid else None
    if not m_valid:
        problems.append(f"line {line_of(text, tag.start())}: opening tag is `{tag.group(0)}` — must be exactly "
                        "<prompt session=fresh> or <prompt session=continue> (the attribute is mandatory)")
    closes = [m.start() for m in re.finditer(re.escape(CLOSE_TAG), text)]
    if len(closes) > 1:
        problems.append("multiple closing tags (lines " + ", ".join(str(line_of(text, c)) for c in closes)
                        + "); a handoff is one block")
    close = closes[-1] if closes else -1
    if close < 0:
        problems.append("no closing </prompt> tag — the closing tag marks where the prompt ends")
        body = text[tag.end():]
    elif close < tag.end():
        problems.append("closing </prompt> appears before the opening tag")
        body = text[tag.end():]
    else:
        body = text[tag.end():close]
        if text[close + len(CLOSE_TAG):].strip():
            problems.append(f"line {line_of(text, close)}: content after </prompt> — the prompt is the turn's "
                            "FINAL output; nothing follows the closing tag")
    if session == "continue" and not re.search(r"session=continue\s*—", body):
        problems.append('session=continue but the body never states its reason clause ("session=continue — <why>", '
                        "one clause right after the title)")
    off = tag.end()
    for needle in cfg.banned:
        rx = r"\s+".join(map(re.escape, needle.split())) or re.escape(needle)
        rx = (r"(?<!\w)" if re.match(r"\w", needle.strip()) else "") + rx + (r"(?!\w)" if re.search(r"\w$", needle.strip()) else "")
        for m in re.finditer(rx, body, re.IGNORECASE):
            problems.append(f"line {line_of(text, off + m.start())}: mentions `{needle}` — a handoff never carries it "
                            "(formal.toml [handoff] banned)")
    ids = "|".join(re.escape(p) for p in cfg.id_prefixes)
    meta = re.compile(r"\b(" + re.escape(cfg.records) + r"/[A-Za-z0-9_./-]*|(?:" + ids + r")-\d{4,})\b")
    named = {m.group(1) for m in meta.finditer(body)}
    if named and not REGISTER_WARNING.search(body):
        first = next(meta.finditer(body))
        problems.append(f"line {line_of(text, off + first.start())}: names {', '.join(sorted(named))} as a source but "
                        "carries no docstring-register warning — a session cites what it was pointed at. Paste one "
                        f"sentence:\n          {REGISTER_PASTE}")
    if cfg.root_dirs:
        root_rel = re.compile(r"(?<!\.\./)\b(" + "|".join(re.escape(d) for d in cfg.root_dirs) + r")/")
        for m in root_rel.finditer(body):
            problems.append(f"line {line_of(text, off + m.start())}: root-relative path `{m.group(0)}…` — paths are "
                            f"relative to {cfg.workspace_name}/, write `../{m.group(1)}/…`")
    instr = cfg.instructions.name
    ws_prefixed = re.compile(r"\b" + re.escape(cfg.workspace_name) + r"/(?!" + re.escape(instr) + r")")
    for m in ws_prefixed.finditer(body):
        problems.append(f"line {line_of(text, off + m.start())}: `{cfg.workspace_name}/`-prefixed path — the receiving "
                        f"session runs from {cfg.workspace_name}/; drop the prefix (only the closing \"per "
                        f"{cfg.workspace_name}/{instr}\" is exempt)")
    if not REFUTE_LINE.search(body):
        problems.append("no `Refute first:` line — the prover session's opening move is a computed refutation attempt at "
                        f"the smallest parameters, and the prompt names them. Paste one line:\n          {REFUTE_PASTE}")
    names = commissioned_names(body)
    if names is None:
        problems.append("no `Commissioned:` line — the landing looks every commissioned declaration up in the manifests "
                        f"(`formal handback --handoff DRAFT`), so the prompt lists them. Paste one line:\n          {COMMISSION_PASTE}")
    elif not names and not COMMISSION_NONE.match(COMMISSION_LINE.search(body).group(1).strip()):
        problems.append("the `Commissioned:` line names no backticked declaration and does not say `none — <why>`. "
                        f"Paste one line:\n          {COMMISSION_PASTE}")
    pieces = set(PIECE.findall(body))
    if len(pieces) >= 2 and not BUNDLE_LINE.search(body):
        problems.append(f"names {len(pieces)} pieces/targets but no `Bundle shape:` line — a multi-piece bundle lands "
                        f"its sink first with the predecessors as hypotheses, or says why not. Paste one line:\n          {BUNDLE_PASTE}")
    if (len(pieces) >= 2 or MULTI_BUNDLE.search(body)) and not BUNDLE_WORDS_WARNING.search(body):
        problems.append("a multi-piece bundle with no sentence keeping its own words out of the docstrings — a session "
                        f"writes what the prompt calls things. Paste one sentence:\n          {BUNDLE_WORDS_PASTE}")
    return problems, session


# --- the handback diff --------------------------------------------------------------------

WITNESS_SUFFIX = "_nonvacuous"
MIN_CONDITIONS = 2
TOKEN_BT = re.compile(r"`([^`\s]+)`")
BOUNDARY = re.compile(r"^\s*\*\*Boundar")
STATEMENT = re.compile(r"^\*\*(Proposition|Theorem|Lemma|Corollary|Definition|Remark) ([\d.]+[a-z]?)")
BOUNDARY_REACH = 40
SIGNATURE = re.compile(r"\b(?:theorem|lemma|def|abbrev|structure|class|inductive|instance)\s+([A-Za-z_][\w.']*)")
WITNESS = re.compile(r"`([^`\s]+_nonvacuous)`")


def views(rs):
    public, private, fields, mods = set(), set(), set(), {}
    for r in rs:
        if r.kind == "decl":
            public.add(r.name)
        elif r.kind == "private":
            private.add(r.name)
        elif r.kind == "field":
            fields.add(r.name)
        elif r.kind == "module":
            mods[r.module] = r.extra
    return public, private - public, fields, mods


def module_of(rs):
    return {r.name: r.module for r in rs if r.kind in ("decl", "private", "field")}


def owed(rs, base_rows=None, min_conditions=MIN_CONDITIONS):
    """(owed, witnessed): theorems with `min_conditions`+ named conditions, split by whether a
    `<theorem>_nonvacuous` exists; with `base_rows`, only theorems absent from the base."""
    conds, names = defaultdict(list), set()
    for r in rs:
        if r.kind == "hypothesis":
            conds[r.name].append(r.extra)
        elif r.kind in ("decl", "private"):
            names.add(r.name)
    base = {r.name for r in base_rows if r.kind in ("decl", "private")} if base_rows else set()
    owed_list, witnessed = [], []
    for thm, cs in sorted(conds.items()):
        if len(cs) < min_conditions or (base_rows is not None and thm in base):
            continue
        (witnessed if thm + WITNESS_SUFFIX in names else owed_list).append((thm, cs))
    return owed_list, witnessed


def commission(text):
    names = commissioned_names(text)
    if names is not None:
        return names, "its Commissioned line"
    found = SIGNATURE.findall(text) + WITNESS.findall(text)
    return list(dict.fromkeys(found)), "declaration keywords and witnesses (no Commissioned line)"


def sort_commission(names, base_names, head_names):
    landed, existing, absent = [], [], []
    for n in names:
        if matches_in(n, head_names - base_names):
            landed.append(n)
        elif matches_in(n, head_names):
            existing.append(n)
        else:
            absent.append(n)
    return landed, existing, absent


def instantiations(new_names, base_public):
    """A new name `P_x` under an existing public `P` of the same namespace, longest prefix first."""
    generics = sorted(base_public, key=len, reverse=True)
    inst = defaultdict(list)
    for n in new_names:
        base = n.split(".")[-1]
        for g in generics:
            gb = g.split(".")[-1]
            if base.startswith(gb + "_") and n.rsplit(".", 1)[0] == g.rsplit(".", 1)[0]:
                inst[g].append(n)
                break
    return inst


STALE_TOLERANCE = 2.0  # seconds


def module_of_file(cfg, f, known):
    """The module a `.lean` path relative to the root holds: under a bound package's root, or, where no
    package binds it, under the workspace as `module_path` reads it, if the manifest knows the module."""
    if not f.endswith(".lean"):
        return None
    for root, pdir in cfg.packages.items():
        p_rel = pdir.relative_to(cfg.root).as_posix()
        prefix = "" if p_rel in ("", ".") else p_rel.rstrip("/") + "/"
        if f.startswith(prefix + root + "/") or f == prefix + root + ".lean":
            return f[len(prefix):-5].replace("/", ".")
    ws_rel = cfg.workspace.relative_to(cfg.root).as_posix()
    ws_prefix = "" if ws_rel in ("", ".") else ws_rel.rstrip("/") + "/"
    if f.startswith(ws_prefix) and (mod := f[len(ws_prefix):-5].replace("/", ".")) in known:
        return mod
    return None


def git(cfg, *args):
    return subprocess.run(["git", *args], cwd=cfg.root, capture_output=True, encoding="utf-8", errors="replace")


def do_handback(cfg, base, handoff):
    handoff_text = None
    if handoff:
        try:
            handoff_text = Path(handoff).read_text(encoding="utf-8")
        except OSError as e:
            print(f"COULD NOT CHECK: unreadable handoff draft ({e})")
            return 2
    g = git(cfg, "rev-parse", "--verify", "--quiet", base)
    if g.returncode != 0:
        why = (g.stderr.strip().splitlines() or ["not a git repository, or no such revision"])[0]
        print(f"COULD NOT CHECK: {base} is not a revision of a git repository at {cfg.root} ({why})")
        return 2
    try:
        base_rows = rows_at(cfg, base)
        if not base_rows:
            print(f"COULD NOT CHECK: no manifest at {base}")
            return 2
        head_rows = list(rows(cfg))
    except ManifestError as e:
        print(f"COULD NOT CHECK: {e}")
        return 2
    ws_rel = cfg.workspace.relative_to(cfg.root).as_posix()
    known = {r.module for r in base_rows + head_rows if r.kind == "module"}
    untracked = [f for f in git(cfg, "ls-files", "--others", "--exclude-standard", "-z", "--", ws_rel).stdout.split("\0")
                 if f.endswith(".lean")]
    # the modules the manifest counts, edited since HEAD: a lakefile or a scratch file is not one
    edited = [f for f in git(cfg, "diff", "--name-only", "--relative", "-z", "HEAD", "--", ws_rel).stdout.split("\0") + untracked
              if (cfg.root / f).is_file() and module_of_file(cfg, f, known)]
    if edited:
        newest = max(edited, key=lambda f: (cfg.root / f).stat().st_mtime)
        # a tolerance: git writes a stash or a checkout in path order, so the manifest may be a moment older
        stale = [m for m in cfg.manifests if m.stat().st_mtime + STALE_TOLERANCE < (cfg.root / newest).stat().st_mtime]
        if stale:
            print(f"COULD NOT CHECK: {', '.join(m.relative_to(cfg.root).as_posix() for m in stale)} is older than {newest}, "
                  "edited since HEAD — the manifest was not regenerated after the last change, so it is not the tree. "
                  f"Regenerate it ({cfg.generate or 'the command formal.toml binds in [manifest] generate'}) and run again.")
            return 2
    b_pub, b_priv, b_fld, b_mod = views(base_rows)
    h_pub, h_priv, h_fld, h_mod = views(head_rows)
    b_all, h_all = b_pub | b_priv, h_pub | h_priv
    h_module_of, b_module_of = module_of(head_rows), module_of(base_rows)
    new_pub, new_priv = sorted(h_pub - b_all), sorted(h_priv - b_all)
    removed = sorted(b_all - h_all)
    to_private, to_public = sorted(b_pub & h_priv), sorted(b_priv & h_pub)
    fld_add, fld_rm = sorted(h_fld - b_fld), sorted(b_fld - h_fld)
    mod_delta = {m: (b_mod.get(m), h_mod.get(m)) for m in set(b_mod) | set(h_mod) if b_mod.get(m) != h_mod.get(m)}
    inst = instantiations(new_pub + new_priv, b_pub)
    print(f"handback: manifest {base} -> working tree ({len(b_all)} -> {len(h_all)} declarations, "
          f"{len(b_mod)} -> {len(h_mod)} modules)")

    def block(title, names):
        print(f"\n{title} ({len(names)}):")
        for n in names:
            print(f"  {n}  [{h_module_of.get(n) or b_module_of.get(n)}]")

    block("NEW PUBLIC", new_pub)
