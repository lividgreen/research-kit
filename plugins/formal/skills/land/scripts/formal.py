def main(argv=None):
    """The command line; a crash exits 2, could not run, never 1, which says problems were found."""
    try:
        return _main(argv)
    except Exception:
        traceback.print_exc()
        print("formal: could not run (the error above)", file=sys.stderr)
        return 2


def _main(argv=None):
    ap = argparse.ArgumentParser(prog="formal", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", help="the project root (default: found above the cwd by formal.toml)")
    ap.add_argument("--selftest", action="store_true")
    sp = ap.add_subparsers(dest="cmd")
    p = sp.add_parser("init"); p.add_argument("--workspace", default="formal"); p.add_argument("--force", action="store_true")
    sp.add_parser("check")
    p = sp.add_parser("handoffcheck"); p.add_argument("draft", nargs="?")
    p = sp.add_parser("handback"); p.add_argument("--base", default="HEAD"); p.add_argument("--handoff")
    p = sp.add_parser("readback"); p.add_argument("names", nargs="+"); p.add_argument("-o", "--out"); p.add_argument("--depth", type=int, default=2)
    p = sp.add_parser("probe", help="report the project and the machine against the prover side's setup; writes nothing"); p.add_argument("--json", action="store_true")
    sp.add_parser("cite", help="every declaration name the documents cite resolves in the manifests")
    sp.add_parser("anchors", help="every [Key] §N, [Key] Theorem N.M and [Key] Appendix X resolves in its document")
    sp.add_parser("register", help="what ships carries none of the bound pattern classes")
    p = sp.add_parser("hypotheses", help="no public theorem shipped at the base gains a named condition"); p.add_argument("--base", default="HEAD")
    p.add_argument("--baseline", help="a pinned baseline file instead of the base revision"); p.add_argument("--update", action="store_true")
    p = sp.add_parser("witnesses", help="theorems with two or more named conditions and no _nonvacuous witness; a report"); p.add_argument("--base")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    if not a.cmd:
        ap.print_help()
        return 0
    if a.cmd == "probe":
        root = Path(a.root).resolve() if a.root else find_root()
        rep_ = probe(root)
        print(json.dumps(rep_, indent=1) if a.json else render_probe(rep_))
        return 0
    root = Path(a.root).resolve() if a.root else find_root()
    try:
        if a.cmd == "init":
            do_init(root, a.workspace, a.force)
            return 0
        if a.cmd == "handoffcheck":
            cfg = Config(root, allow_missing=True)
            text = Path(a.draft).read_text(encoding="utf-8") if a.draft else sys.stdin.read()
            try:
                problems, _ = check_handoff(text, cfg)
            except ValueError as e:
                print(f"COULD NOT CHECK: {e}")
                return 2
            if problems:
                for pr in problems:
                    print(f"HANDOFF {pr}")
                print(f"\n{len(problems)} violation(s). Fix and re-run before emitting.")
                return 1
            print("handoffcheck: structurally clean (content fidelity is still yours to re-read)"
                  + ("" if cfg.bound else "; no formal.toml found, the default bindings were used"))
            return 0
        try:
            cfg = Config(root)
        except (Refused, tomllib.TOMLDecodeError, UnicodeDecodeError) as e:  # no bindings to run on: could not run, not a problem found
            print(f"COULD NOT CHECK: {e}")
            return 2
        if a.cmd == "check":
            return do_check(cfg)
        if a.cmd == "handback":
            return do_handback(cfg, a.base, a.handoff)
        if a.cmd == "readback":
            return do_readback(cfg, a.names, a.out, a.depth)
        if a.cmd == "cite":
            return do_cite(cfg)
        if a.cmd == "anchors":
            return do_anchors(cfg)
        if a.cmd == "register":
            return do_register(cfg)
        if a.cmd == "hypotheses":
            return do_hypotheses(cfg, a.base, a.baseline, a.update)
        if a.cmd == "witnesses":
            return do_witnesses(cfg, a.base)
    except Refused as e:
        print(f"formal: refused — {e}")
        return 1
    except OSError as e:
        print(f"COULD NOT CHECK: {e}")
        return 2
    return 0


