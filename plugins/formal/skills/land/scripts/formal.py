PROBE_SKIP = {".git", ".lake", "node_modules", ".venv", "build", "dist"}
LIB_RE = re.compile(r"lean_lib\s+(?:«([^»]+)»|([A-Za-z_][\w.]*))")


def lake_roots(ws):
    """The library roots a workspace's lakefile declares (lakefile.toml's [[lean_lib]] names, or
    lakefile.lean's `lean_lib` declarations), and the package name."""
    toml = ws / "lakefile.toml"
    if toml.is_file():
        try:
            raw = tomllib.loads(toml.read_text(encoding="utf-8"))
        except (tomllib.TOMLDecodeError, UnicodeDecodeError):
            return None, []
        roots = [str(r).split(".")[0] for lib in raw.get("lean_lib", []) if lib.get("name")
                 for r in (lib.get("roots") or [lib["name"]])]
        return raw.get("name"), list(dict.fromkeys(roots))
    lean = ws / "lakefile.lean"
    if lean.is_file():
        text = lean.read_text(encoding="utf-8", errors="replace")
        m = re.search(r"package\s+(?:«([^»]+)»|([A-Za-z_][\w.]*))", text)
        return (m.group(1) or m.group(2)) if m else None, [a or b for a, b in LIB_RE.findall(text)]
    return None, []


def lake_lib_modules(ws):
    """The root modules a lakefile.toml's `[[lean_lib]]` tables declare, whole (`Lib.Tests`, not `Lib`)."""
    toml = ws / "lakefile.toml"
    try:
        raw = tomllib.loads(toml.read_text(encoding="utf-8")) if toml.is_file() else {}
    except (tomllib.TOMLDecodeError, UnicodeDecodeError):
        return []
    return [str(r) for lib in raw.get("lean_lib", []) if lib.get("name") for r in (lib.get("roots") or [lib["name"]])]


def lake_requires(ws):
    """The directories a workspace's lakefile requires by path."""
    toml, lean = ws / "lakefile.toml", ws / "lakefile.lean"
    if toml.is_file():
        try:
            raw = tomllib.loads(toml.read_text(encoding="utf-8"))
        except (tomllib.TOMLDecodeError, UnicodeDecodeError):
            return []
        return [(ws / req["path"]).resolve() for req in raw.get("require", []) if isinstance(req.get("path"), str)]
    if lean.is_file():
        text = lean.read_text(encoding="utf-8", errors="replace")
        return [(ws / p).resolve() for p in re.findall(r'^\s*require\s+[^\n]*?\bfrom\s+"([^"]+)"', text, re.M)]
    return []


def has_lakefile(d):
    return (d / "lakefile.toml").is_file() or (d / "lakefile.lean").is_file()


def manifest_commands(root, ws, packages):
    """(out files from the root, generate commands run in the workspace): one per package, every root of
    the workspace passed as `--own`, so a condition defined in another package is still a named one."""
    own = ",".join(r for p in packages for r in p["roots"])
    files, cmds = [], []
    for p in packages:
        name = "decls.txt" if len(packages) == 1 else f"{p['package'] or Path(p['dir']).name}-decls.txt"
        out = Path(os.path.relpath(root / "scripts" / name, ws)).as_posix()
        files.append(f"scripts/{name}")
        cmds.append(f"lake env lean --run DeclManifest.lean --roots {','.join(p['roots']) or '<Root>'} "
                    + (f"--own {own} " if len(packages) > 1 else "") + f"--out {out}")
    return files, cmds


