DECL_KINDS = ("theorem", "lemma", "def", "abbrev", "structure", "class", "inductive", "instance", "opaque", "axiom")
DEF_LIKE = {"def", "abbrev", "structure", "class", "inductive", "opaque", "instance"}
MODIFIERS = r"(?:(?:public|private|protected|noncomputable|nonrec|unsafe|partial|scoped|local)\s+)*"
DECL_LINE = re.compile(r"^(?:@\[[^\]]*\]\s+)?" + MODIFIERS + r"(" + "|".join(DECL_KINDS) + r")\s+(?:\{[^}]*\}\s+)?([^\s:(\[{]+)")
SCOPE_LINE = re.compile(
    r"^(?:namespace|section|end\b|noncomputable section|variable|open\b|universe|"
    r"(?:local |scoped )?(?:notation|infix|infixl|infixr|prefix|postfix|macro|macro_rules|syntax)|attribute \[local)")
MODIFIER_ABOVE = re.compile(r"^(?:@\[.*\]\s*$|(?:omit|include|set_option|open)\b.*\bin\s*$)")
OPEN_BRACKETS, CLOSE_BRACKETS = "([{⟨⦃", ")]}⟩⦄"
TOKEN = re.compile(r"[^\s()\[\]{}⟨⟩,;:=\"`]+")
QUANT = re.compile(r"(?:∀|∃|fun|λ)\s+([^,]{0,120}?)(?:,|=>|↦)")
LAMBDA = re.compile(r"(?:fun|λ)\s+([^=]{0,120}?)=>")
MATCH_ARM = re.compile(r"^\s*\|([^=]{0,200}?)=>", re.M)
BINDER_GROUP = re.compile(r"[({⦃]\s*([^:()}{⦃⦄]{1,80}?)\s*:")
SET_BUILDER = re.compile(r"\{\s*([^|{}]{0,60}?)\s*(?:\||//)")
UPSTREAM_PREFIX = ("Nat.", "List.", "Finset.", "Set.", "Function.", "Real.", "ENNReal.", "Part.")
IMPORT_LINE = re.compile(r"^\s*(?:public\s+|private\s+)?import\s+(?:all\s+)?([A-Za-z0-9_.]+)")
NAMESPACE_LINE = re.compile(r"^namespace\s+(\S+)")
SECTION_LINE = re.compile(r"^(?:@\[[^\]]*\]\s*)?(?:(?:public|private|noncomputable)\s+)*section\b")
END_LINE = re.compile(r"^end\b")


LITERAL = re.compile(r'"(?:\\.|[^"\\])*"|«[^»\n]*»|(?<![\w.\'])\'(?:\\[^\']+|[^\\\'\n])\'')


def comment_spans(text):
    """The (start, end) of each comment, as Lean reads them: a block comment nests, a line comment runs to
    its line's end, and a `--` or `/-` inside a string, a character literal or a «quoted» name is the literal's."""
    i, n = 0, len(text)
    while i < n:
        if text.startswith("/-", i):
            start, depth, i = i, 1, i + 2
            while i < n and depth:
                if text.startswith("/-", i):
                    depth, i = depth + 1, i + 2
                elif text.startswith("-/", i):
                    depth, i = depth - 1, i + 2
                else:
                    i += 1
            yield start, i
        elif text.startswith("--", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            yield i, j
            i = j
        else:
            m = LITERAL.match(text, i)
            i = m.end() if m else i + 1


def strip_comments(text):
    """The text without its comments, and without the blanks before a line comment."""
    out, pos = [], 0
    for start, end in comment_spans(text):
        piece = text[pos:start]
        out.append(piece.rstrip(" \t") if text.startswith("--", start) else piece)
        pos = end
    return "".join(out) + text[pos:]


class Reader:
    """The read-back builder over one project's bindings and manifests."""

    def __init__(self, cfg):
        self.cfg = cfg
        self.names, self.instances = {}, {}
        for r in rows(cfg):
            if r.kind in ("decl", "private"):
                self.names[r.name] = r.module
            elif r.kind == "instance":
                self.instances.setdefault(r.name, set()).add(r.extra)
        self.instances = {n: sorted(cs) for n, cs in self.instances.items()}
        self._closure, self._files, self._comments = {}, {}, {}

    def resolve(self, tok, prefer_module=None):
        hits = {n for n in self.names if n == tok or n.endswith("." + tok) or n.split(".")[-1] == tok}
        if prefer_module:
            same = {n for n in hits if self.names[n] == prefer_module}
            if same:
                return same
        return hits

    def resolve_target(self, tok):
        """A named declaration: exact, module-qualified, or a bare name resolving in ONE module;
        a bare name in several modules is refused as ambiguous."""
        if tok in self.names:
            return {tok}, None
        if "." in tok:
            mod, bare = tok.rsplit(".", 1)
            hits = {n for n in self.names if n.split(".")[-1] == bare
                    and (self.names[n] == mod or self.names[n].endswith("." + mod))}
            if hits:
                return hits, None
        hits = self.resolve(tok)
        if len({self.names[n] for n in hits}) > 1:
            return set(), (f"{tok} (ambiguous across modules: " + ", ".join(sorted(hits))
                           + " — name it by module, as `Module.name`, or by its qualified name)")
        return hits, None

    def file_lines(self, path):
        if path not in self._files:
            self._files[path] = path.read_text(encoding="utf-8").split("\n")
        return self._files[path]

    def comment_lines(self, path):
        if path not in self._comments:
            text = "\n".join(self.file_lines(path))
            bad = set()
            for start, end in comment_spans(text):
                if text.startswith("/-", start):
                    bad.update(range(text.count("\n", 0, start), text.count("\n", 0, end) + 1))
            self._comments[path] = bad
        return self._comments[path]

    def import_closure(self, module):
        """Modules a module can see: itself and its transitive imports among the project's."""
        if module in self._closure:
            return self._closure[module]
        seen, queue = {module}, [module]
        while queue:
            m = queue.pop()
            path = module_path(self.cfg, m)
            if not path.is_file():
                continue
            for ln in self.file_lines(path):
                if ln.startswith(("theorem", "lemma", "def", "namespace", "@[")):
                    break
                hit = IMPORT_LINE.match(ln)
                if hit and hit.group(1) not in seen and hit.group(1).split(".")[0] in self.cfg.packages:
                    seen.add(hit.group(1))
                    queue.append(hit.group(1))
        self._closure[module] = seen
        return seen

    @staticmethod
    def find_decl(lines, qname, in_comment=frozenset()):
        stack, by_last = [], []
        base = qname.split(".")[-1]
        for i, ln in enumerate(lines):
            if i in in_comment:
                continue
            if m := NAMESPACE_LINE.match(ln):
                stack.append(m.group(1).split("."))
                continue
            if SECTION_LINE.match(ln) or ln.startswith("mutual"):
                stack.append([])
                continue
            if END_LINE.match(ln):
                if stack:
                    stack.pop()
                continue
            m = DECL_LINE.match(ln)
            if not m:
                continue
            declared = m.group(2)
            full = (declared[len("_root_."):] if declared.startswith("_root_.")
                    else ".".join([c for part in stack for c in part] + [declared]))
            if full == qname:
                return i, m.group(1)
            if declared.split(".")[-1] == base:
                by_last.append((i, m.group(1)))
        # no exact match: the last component stands for it only when one declaration of the file has it,
        # never the first of several, which would put another statement under the target's name
        return by_last[0] if len(by_last) == 1 else (None, None)

    @staticmethod
    def cut_at_top_level_assign(text):
        depth, i = 0, 0
        while i < len(text) - 1:
            c = text[i]
            if c in OPEN_BRACKETS:
                depth += 1
            elif c in CLOSE_BRACKETS:
                depth = max(0, depth - 1)
            elif depth == 0 and text[i] == ":" and text[i + 1] == "=":
                return text[:i].rstrip()
            i += 1
        return text

    @staticmethod
    def cut_at_match_arms(text):
        lines = text.split("\n")
        for i, ln in enumerate(lines[1:], start=1):
            if ln.lstrip().startswith("| "):
                return "\n".join(lines[:i]).rstrip()
        return text

    def source_block(self, lines, i, kind):
        start = i
        while start > 0:
            above = lines[start - 1].strip()
            if above.endswith("-/"):
                k = start - 1
                while k > 0 and not lines[k].lstrip().startswith(("/--", "/-!", "/-")):
                    k -= 1
                if MODIFIER_ABOVE.match(lines[k - 1].strip()) if k > 0 else False:
                    start = k
                    continue
                break
            if MODIFIER_ABOVE.match(above):
                start -= 1
                continue
            break
        j = i + 1
        while j < len(lines) and (lines[j].strip() == "" or lines[j][0] in " \t"):
            j += 1
        body = lines[start:j]
        while body and body[-1].strip() == "":
            body.pop()
        text = strip_comments("\n".join(body))
        if kind in ("theorem", "lemma"):
            text = self.cut_at_match_arms(self.cut_at_top_level_assign(text))
            text += "\n  -- (proof omitted: the statement is what is read back)"
        return text, start

    @staticmethod
    def scope_lines(lines, upto, in_comment=frozenset()):
        out, k = [], 0
        while k < upto:
            ln = lines[k]
            if k not in in_comment and SCOPE_LINE.match(ln) and not re.search(r"\bin\s*$", ln):
                block = [ln]
                k2 = k + 1
                while k2 < upto and lines[k2].strip() and lines[k2][0] in " \t" and k2 not in in_comment:
                    block.append(lines[k2])
                    k2 += 1
                out.append((k + 1, strip_comments("\n".join(block))))
                k = k2
            else:
                k += 1
        return out

    @staticmethod
    def bound_names(text):
        out = set()
        for rx in (QUANT, LAMBDA, MATCH_ARM, SET_BUILDER):
            for m in rx.finditer(text):
                out.update(TOKEN.findall(m.group(1).split(":")[0]))
        for m in BINDER_GROUP.finditer(text):
            out.update(TOKEN.findall(m.group(1)))
        return out

    def names_in(self, text, prefer_module, scope_text=""):
        """Project-local names a block mentions, and the dot-notation tokens declined."""
        found, dotted = OrderedDict(), OrderedDict()
        bound = self.bound_names(text + "\n" + scope_text)
        visible = self.import_closure(prefer_module) if prefer_module else None
        for m in TOKEN.finditer(text):
            raw = m.group(0)
            tok = raw.strip(".!?⁻¹")
            if not tok or tok[0].isdigit() or tok.startswith(UPSTREAM_PREFIX):
                continue
            if len(tok) <= 2 and m.start() > 0 and text[m.start() - 1] == "=":
                continue
            hits = self.resolve(tok, prefer_module)
            if visible is not None:
                hits = {n for n in hits if self.names[n] in visible}
            if not hits and "." in tok and not raw.startswith("."):
                tok = tok.split(".")[0]
                hits = self.resolve(tok, prefer_module) if tok else set()
                if visible is not None:
                    hits = {n for n in hits if self.names[n] in visible}
            if not hits:
                continue
            own = any(self.names[n] == prefer_module for n in hits)
            if raw.startswith(".") and not own:
                dotted.setdefault(tok, set()).update(hits)
                continue
            if len(tok) <= 2 and tok in bound and not own:
                continue
            for n in sorted(hits):
                found.setdefault(n, tok)
        return found, dotted

    def build(self, targets, depth):
        sections, missing, dotted, cut, theorems_named = OrderedDict(), [], OrderedDict(), OrderedDict(), OrderedDict()
        queue = [(t, 0, None) for t in targets]
        while queue:
            tok, d, prefer = queue.pop(0)
            if d == 0:
                hits, why = self.resolve_target(tok)
            else:
                hits, why = (self.resolve(tok, prefer) if tok not in self.names else {tok}), None
            if not hits:
                missing.append(why or tok)
                continue
            for qname in sorted(hits):
                if qname in sections:
                    continue
                module = self.names[qname]
                path = module_path(self.cfg, module)
                if not path.is_file():
                    missing.append(f"{qname} (no file for {module})")
                    continue
                lines = self.file_lines(path)
                i, kind = self.find_decl(lines, qname, self.comment_lines(path))
                if i is None:
                    missing.append(f"{qname} (declaration line not found in {path.name})")
                    continue
                if d > 0 and kind not in DEF_LIKE:
                    theorems_named[qname] = f"{path.relative_to(self.cfg.root)}:{i + 1}"
                    continue
                text, start = self.source_block(lines, i, kind)
                scope = self.scope_lines(lines, start, self.comment_lines(path))
                sections[qname] = {"module": module, "file": str(path.relative_to(self.cfg.root)), "line": start + 1,
                                   "kind": kind, "text": text, "depth": d, "scope": scope,
                                   "instances": self.instances.get(qname, []) if d == 0 else []}
                found, dots = self.names_in(text, module, "\n".join(t for _, t in scope))
                for tok3, cands in dots.items():
                    dotted.setdefault(tok3, set()).update(cands)
                for n2, tok2 in found.items():
                    if n2 == qname or n2 in sections:
                        continue
                    if d + 1 > depth:
                        cut.setdefault(n2, tok2)
                    else:
                        queue.append((n2, d + 1, module))
        for n in list(cut):
            if n in sections:
                del cut[n]
        for tok in list(dotted):
            if not (dotted[tok] - set(sections)):
                del dotted[tok]
        return sections, missing, cut, theorems_named, dotted


