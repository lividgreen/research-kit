def commissioned_names(text):
    """The names a prompt's `Commissioned:` line lists; [] for `none`; None with no line."""
    m = COMMISSION_LINE.search(text)
    if not m:
        return None
    rest = m.group(1).strip()
    if COMMISSION_NONE.match(rest):
        return []
    return list(dict.fromkeys(COMMISSION_NAME.findall(rest)))


def line_of(text, pos):
    return text.count("\n", 0, pos) + 1


def record_pattern(cfg):
    """What names a record as a source: a path under a records prefix, a record id, the log's or the
    registry's file name, or a reference key of the project's own form."""
    alts = [re.escape(p.rstrip("/")) + r"/[A-Za-z0-9_./-]*(?<![.-])" for p in cfg.records if p.strip("/")]
    if cfg.id_prefixes:
        alts.append(r"(?:" + "|".join(re.escape(p) for p in cfg.id_prefixes) + r")-\d{4,}(?!\w)")
    alts += [re.escape(n) + r"(?!\w)" for n in cfg.meta_names]
    alts += [f"(?:{k})" for k in cfg.key_patterns]
    return re.compile(r"(?<![\w.-])(" + "|".join(alts) + ")") if alts else re.compile(r"(?!)")


def check_handoff(text, cfg):
    """(problems, session) for one draft; raises ValueError with no prompt block at all."""
    opens = list(OPEN_TAG.finditer(text))
    if not opens:
        raise ValueError("no <prompt ...> block found in the input")
    problems = []
    if len(opens) > 1:
        problems.append("multiple opening tags (lines " + ", ".join(str(line_of(text, m.start())) for m in opens)
                        + "); a handoff is one block")
    tag = opens[0]
    m_valid = OPEN_TAG_VALID.fullmatch(tag.group(0))
    session = m_valid.group(1) if m_valid else None
    if not m_valid:
        problems.append(f"line {line_of(text, tag.start())}: opening tag is `{tag.group(0)}` — must be exactly "
                        "<prompt session=fresh> or <prompt session=continue> (the attribute is mandatory)")
    closes = [m.start() for m in re.finditer(re.escape(CLOSE_TAG), text)]
    if len(closes) > 1:
        problems.append("multiple closing tags (lines " + ", ".join(str(line_of(text, c)) for c in closes)
                        + "); a handoff is one block")
    close = closes[-1] if closes else -1
    if close < 0:
        problems.append("no closing </prompt> tag — the closing tag marks where the prompt ends")
        body = text[tag.end():]
    elif close < tag.end():
        problems.append("closing </prompt> appears before the opening tag")
        body = text[tag.end():]
    else:
        body = text[tag.end():close]
        if text[close + len(CLOSE_TAG):].strip():
            problems.append(f"line {line_of(text, close)}: content after </prompt> — the prompt is the turn's "
                            "FINAL output; nothing follows the closing tag")
    if session == "continue" and not re.search(r"session=continue\s*—", body):
        problems.append('session=continue but the body never states its reason clause ("session=continue — <why>", '
                        "one clause right after the title)")
    off = tag.end()
    for needle in cfg.banned:
        rx = r"\s+".join(map(re.escape, needle.split())) or re.escape(needle)
        rx = (r"(?<!\w)" if re.match(r"\w", needle.strip()) else "") + rx + (r"(?!\w)" if re.search(r"\w$", needle.strip()) else "")
        for m in re.finditer(rx, body, re.IGNORECASE):
            problems.append(f"line {line_of(text, off + m.start())}: mentions `{needle}` — a handoff never carries it "
                            "(formal.toml [handoff] banned)")
    meta = record_pattern(cfg)
    named = {m.group(1) for m in meta.finditer(body)}
    if named and not REGISTER_WARNING.search(body):
        first = next(meta.finditer(body))
        problems.append(f"line {line_of(text, off + first.start())}: names {', '.join(sorted(named))} as a source but "
                        "carries no docstring-register warning — a session cites what it was pointed at. Paste one "
                        f"sentence:\n          {REGISTER_PASTE}")
    if cfg.root_dirs:
        root_rel = re.compile(r"(?<!\.\./)\b(" + "|".join(re.escape(d) for d in cfg.root_dirs) + r")/")
        for m in root_rel.finditer(body):
            problems.append(f"line {line_of(text, off + m.start())}: root-relative path `{m.group(0)}…` — paths are "
                            f"relative to {cfg.workspace_name}/, write `../{m.group(1)}/…`")
    instr = cfg.instructions.name
    ws_prefixed = re.compile(r"\b" + re.escape(cfg.workspace_name) + r"/(?!" + re.escape(instr) + r")")
    for m in ws_prefixed.finditer(body):
        problems.append(f"line {line_of(text, off + m.start())}: `{cfg.workspace_name}/`-prefixed path — the receiving "
                        f"session runs from {cfg.workspace_name}/; drop the prefix (only the closing \"per "
                        f"{cfg.workspace_name}/{instr}\" is exempt)")
    if not REFUTE_LINE.search(body):
        problems.append("no `Refute first:` line — the prover session's opening move is a computed refutation attempt at "
                        f"the smallest parameters, and the prompt names them. Paste one line:\n          {REFUTE_PASTE}")
    names = commissioned_names(body)
    if names is None:
        problems.append("no `Commissioned:` line — the landing looks every commissioned declaration up in the manifests "
                        f"(`formal handback --handoff DRAFT`), so the prompt lists them. Paste one line:\n          {COMMISSION_PASTE}")
    elif not names and not COMMISSION_NONE.match(COMMISSION_LINE.search(body).group(1).strip()):
        problems.append("the `Commissioned:` line names no backticked declaration and does not say `none — <why>`. "
                        f"Paste one line:\n          {COMMISSION_PASTE}")
    pieces = set(PIECE.findall(body))
    if len(pieces) >= 2 and not BUNDLE_LINE.search(body):
        problems.append(f"names {len(pieces)} pieces/targets but no `Bundle shape:` line — a multi-piece bundle lands "
                        f"its sink first with the predecessors as hypotheses, or says why not. Paste one line:\n          {BUNDLE_PASTE}")
    if (len(pieces) >= 2 or MULTI_BUNDLE.search(body)) and not BUNDLE_WORDS_WARNING.search(body):
        problems.append("a multi-piece bundle with no sentence keeping its own words out of the docstrings — a session "
                        f"writes what the prompt calls things. Paste one sentence:\n          {BUNDLE_WORDS_PASTE}")
    return problems, session


