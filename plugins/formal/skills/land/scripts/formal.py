#!/usr/bin/env python3
"""formal — the prover side's CLI: the bindings, the manifest grammar, the handoff check,
the handback diff and the read-back packet.

A project that pairs its documents with a machine-checked library binds the prover side in
`formal.toml` at its root: the workspace directory and the prover session's standing
instructions, the declaration manifests the build regenerates (one text file per package in
the row grammar below), the library roots with the package directory each sits in, the
documents whose cited declaration names and anchors are read, what ships and the register it
must not carry, and the words a handoff must not carry.

    formal [--root DIR] <command>          the project root, found above the cwd by formal.toml otherwise
    formal probe [--json]                  what the prover side's setup has and lacks; writes nothing
    formal init [--workspace DIR] [--force]
                                           write formal.toml with every binding explained
    formal check                           the manifests parse and are the tree's, the bindings resolve
    formal handoffcheck DRAFT              the decidable invariants of a handoff prompt
    formal handback [--base REV] [--handoff DRAFT]
                                           what a landing changed, read from the tree
    formal readback NAME... [-o FILE] [--depth N]
                                           a landed statement for a cold reader, stripped
    formal cite                            every declaration name the documents cite resolves
    formal anchors                         every `[Key] §N` of the Lean files resolves in its document
    formal register                        what ships carries none of the bound pattern classes
    formal hypotheses [--base REV | --baseline FILE [--update]]
                                           no shipped public theorem gains a named condition
    formal witnesses [--base REV]          theorems owing a joint-satisfiability witness; a report

The manifest's row grammar, which `DeclManifest.lean` beside this script writes for a Lean
package and any prover's declaration list may follow:

    module <module> <count>                a module and how many declarations it counts
    <module> <name>                        a public declaration
    private <module> <name>                a private one (counted, not citable from outside)
    field <module> <name>                  a structure projection (citable, not counted)
    hypothesis <module> <theorem> <cond>   a public theorem's named condition
    instance <module> <theorem> <class>    a class one of its instance binders carries

Exit codes: 0 clean; 1 problems found (each printed with its place); 2 could not run — a
distinct code, so an exit-code reader never mistakes "did not run" for "clean".
"""

