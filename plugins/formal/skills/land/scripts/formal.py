def path_rx(pattern):
    """A path pattern as a regular expression: `**/` any directories, `*` and `?` within one; a pattern
    with no wildcard also names everything under it."""
    pattern = re.sub(r"^(?:\./)+", "", pattern)
    if pattern in ("", "."):
        return re.compile(r".*\Z")
    out, i = "", 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out, i = out + "(?:.*/)?", i + 3
        elif pattern.startswith("**", i):
            out, i = out + ".*", i + 2
        elif pattern[i] == "*":
            out, i = out + "[^/]*", i + 1
        elif pattern[i] == "?":
            out, i = out + "[^/]", i + 1
        else:
            out, i = out + re.escape(pattern[i]), i + 1
    if not any(c in pattern for c in "*?"):
        out = re.escape(pattern.rstrip("/")) + "(?:/.*)?"
    return re.compile(out + r"\Z")


