def do_check(cfg):
    problems = []
    if not cfg.workspace.is_dir():
        problems.append(f"workspace {cfg.workspace_name}/ is not a directory")
    if not cfg.instructions.is_file():
        problems.append(f"the prover session's instructions {cfg.instructions} do not exist")
    for root, d in cfg.packages.items():
        if not (d / f"{root}.lean").is_file() and not (d / root).is_dir():
            problems.append(f"package root {root}: neither {root}.lean nor {root}/ under {d}")
    counts = defaultdict(int)
    try:
        for r in rows(cfg):
            counts[r.kind] += 1
    except ManifestError as e:
        problems.append(str(e))
    for p in problems:
        print(f"formal check: {p}")
    kinds = ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) or "no rows"
    print(f"formal check: {len(problems)} problem(s); manifests {', '.join(str(m.relative_to(cfg.root)) for m in cfg.manifests)} "
          f"({kinds}); packages {', '.join(cfg.packages) or 'NONE BOUND'}; documents {', '.join(cfg.scan)}; "
          f"the prover tree itself is not built or read here")
    return 1 if problems else 0


